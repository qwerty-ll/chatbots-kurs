# Тетрадь урока 2. Бот принимает решения
# Учитель печатает этот код на проекторе по этапам. Ученики пишут за ним в своей тетради.
# Метка «# ЭТАП N: ...» отделяет этапы. Код этапа — всё до следующей метки.

# ЭТАП 1: Светофор (if и else)
light = input("Цвет светофора? ")
if light == "зеленый":
    print("Можно идти!")
else:
    print("Стоим!")

# ЭТАП 2: Справочник (elif)
q = input("Твой вопрос: ")
if q == "привет":
    print("Здравствуй!")
elif q == "цена":
    print("Занятия бесплатные!")
elif q == "пока":
    print("До встречи!")
else:
    print("Я пока не понял вопрос.")

# ЭТАП 3: Бот понимает фразы (lower, strip, in, or)
q = input("Ещё вопрос: ").lower().strip()
if "привет" in q or "здравств" in q:
    print("Здравствуй! Чем могу помочь?")
elif "цена" in q or "стоит" in q:
    print("Занятия бесплатные!")
elif "адрес" in q or "где" in q:
    print("Кабинет 305, второй этаж.")
else:
    print("Я пока не понял вопрос.")

# ЭТАП 4: Квест (флажок и вложенное условие)
has_card = False
choice = input("Дверь или шкаф? ").lower().strip()
if choice == "шкаф":
    print("Ты находишь ключ-карту!")
    has_card = True
code = input("Код лифта (7 + 8 * 2): ")
if code == "23":
    if has_card:
        print("ПОБЕДА!")
    else:
        print("Нужна карта. КОНЕЦ.")
else:
    print("Неверный код. КОНЕЦ.")
