def generate():
    os.makedirs(GAMES_DIR, exist_ok=True)
    print(f"Генерация курса в {GAMES_DIR}...")
    for l_data in LESSONS_DATA:
        lnum = l_data["lesson"]
        ldir = os.path.join(GAMES_DIR, f"l{lnum:02d}")
        os.makedirs(ldir, exist_ok=True)

        lesson_json = {
            "lesson": lnum,
            "title": l_data["title"],
            "part": l_data.get("part", 1),
            "part_title": l_data.get("part_title", ""),
            "steps": l_data["steps"],
            "theory": l_data["theory"]
        }
        with open(os.path.join(ldir, "lesson.json"), "w", encoding="utf-8") as f:
            json.dump(lesson_json, f, ensure_ascii=False, indent=2)

        for t_info in l_data["tasks"]:
            tdir = os.path.join(ldir, t_info["folder"])
            os.makedirs(tdir, exist_ok=True)

            with open(os.path.join(tdir, "task.json"), "w", encoding="utf-8") as f:
                json.dump(t_info["task"], f, ensure_ascii=False, indent=2)

            with open(os.path.join(tdir, "start.py"), "w", encoding="utf-8") as f:
                f.write(t_info["start"])

            with open(os.path.join(tdir, "solution.py"), "w", encoding="utf-8") as f:
                f.write(t_info["solution"])

    print("Генерация завершена успешно!")


if __name__ == "__main__":
    generate()
