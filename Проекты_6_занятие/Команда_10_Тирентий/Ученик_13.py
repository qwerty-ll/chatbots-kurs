import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def training_tip():
    tips = [
        "Сегодня сделай акцент на технике, а не на весе — это даст больший прогресс.",
        "Не забывай про разминку: 5–10 минут снизят риск травм.",
        "Не забудь про питание — это один из ключевых моментов: без правильной еды прогресса не будет.",
        "Во время разминки не делай резких движений.",
    ]
    return random.choice(tips)


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def exercise_technique(exercise_name):
    exercise_name = exercise_name.lower().strip()
    exercises = {
        "подтягивания": "Подтягивания: держи ноги прямо, не сгибай и дотягивайся подбородком до перекладины.",
        "отжимания": "Отжимания: спина прямая, локти под 45°, опускайся почти до пола.",
        "приседания": "Приседания: колени смотрят туда же, куда носки, спина прямая, пятки не отрывай.",
        "планка": "Планка: тело — прямая линия, живот напряжён, не прогибайся в пояснице.",
    }
    return exercises.get(exercise_name, f"Про упражнение «{exercise_name}» пока не знаю — начни с лёгкого веса и следи за техникой.")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("training_tip", "Даёт совет дня для тренировки и правильного питания спортсмена."),
    make_tool("exercise_technique", "Объясняет правильную технику упражнения.",
              {"exercise_name": {"type": "string", "description": "Упражнение: подтягивания, отжимания, приседания, планка"}},
              ["exercise_name"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "training_tip": lambda args: training_tip(),
    "exercise_technique": lambda args: exercise_technique(args["exercise_name"]),
}

# ▶ Запусти этот файл — с тобой поговорит агент только с ТВОИМИ инструментами.
# Наш_бот.py этот кусок не запускает: он берёт отсюда только TOOLS и FUNCTIONS.
if __name__ == "__main__":
    from agent import agent_answer

    messages = [{"role": "system", "content": "Ты помощник. Если подходит инструмент — используй его."}]
    while True:
        text = input("Ты: ").strip()
        if text == "/exit":
            break
        messages.append({"role": "user", "content": text})
        answer = agent_answer(messages, TOOLS, FUNCTIONS)
        messages.append({"role": "assistant", "content": answer})
        print("Агент:", answer)
