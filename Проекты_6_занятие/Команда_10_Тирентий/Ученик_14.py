import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def dish_secret():
    return random.choice([
        "Секрет пышного омлета — щепотка соды и крышка на сковороде.",
        "Секрет вкусной гречки — обжарь её 2 минуты на сухой сковороде перед варкой.",
        "Секрет румяной курицы — смажь её мёдом за 10 минут до готовности.",
        "Секрет нежного пюре — добавляй горячее молоко, а не холодное.",
    ])


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def dish_recommendation(dish):
    pairs = {
        "курица": "К курице подойдут рис и свежий салат — сытно и полезно для спортсмена.",
        "рыба": "К рыбе подай отварной картофель и лимон.",
        "макароны": "К макаронам добавь тёртый сыр и овощи.",
        "омлет": "К омлету — помидоры и цельнозерновой хлеб, отличный завтрак перед тренировкой.",
    }
    return pairs.get(dish.lower().strip(), f"К блюду «{dish}» подай овощи и стакан воды — не ошибёшься!")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("dish_secret", "Сказать случайный секрет приготовления блюда."),
    make_tool("dish_recommendation", "Сказать, что подать к блюду (гарнир, напиток).",
              {"dish": {"type": "string", "description": "Блюдо, например: курица, рыба, омлет"}}, ["dish"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "dish_secret": lambda args: dish_secret(),
    "dish_recommendation": lambda args: dish_recommendation(args["dish"]),
}

# ▶ Запусти этот файл — с тобой поговорит агент только с ТВОИМИ инструментами.
# Наш_бот.py этот кусок не запускает: он берёт отсюда только TOOLS и FUNCTIONS.
if __name__ == "__main__":
    from agent import agent_answer

    messages = [{"role": "system", "content": "Ты помощник. Если подходит инструмент — используй его."}]
    while True:
        text = input("Ты: ").strip()
        if text == "/exit":
            break
        messages.append({"role": "user", "content": text})
        answer = agent_answer(messages, TOOLS, FUNCTIONS)
        messages.append({"role": "assistant", "content": answer})
        print("Агент:", answer)
