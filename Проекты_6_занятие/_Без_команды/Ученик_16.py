import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def random_fact():
    return random.choice([
        "Осьминог имеет три сердца и голубую кровь.",
        "Мёд не портится — его находили в египетских пирамидах съедобным.",
        "Улитка может спать до трёх лет.",
        "На Венере день длиннее, чем год.",
    ])


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def check_answer(answer):
    # Загадка: «Что можно увидеть с закрытыми глазами?» — правильный ответ: сон
    if "сон" in answer.lower():
        return "Верно! С закрытыми глазами можно увидеть сон. 🎉"
    return f"«{answer}» — не угадал. Подсказка: это бывает ночью. Попробуй ещё!"


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("random_fact", "Рассказывает случайный удивительный факт."),
    make_tool("check_answer", "Проверяет ответ на загадку «Что можно увидеть с закрытыми глазами?».",
              {"answer": {"type": "string", "description": "Ответ пользователя на загадку"}}, ["answer"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "random_fact": lambda args: random_fact(),
    "check_answer": lambda args: check_answer(args["answer"]),
}

# ▶ Запусти этот файл — с тобой поговорит агент только с ТВОИМИ инструментами.
# Наш_бот.py этот кусок не запускает: он берёт отсюда только TOOLS и FUNCTIONS.
if __name__ == "__main__":
    from agent import agent_answer

    messages = [{"role": "system", "content": "Ты бот «Знайка»: рассказываешь удивительные факты и загадываешь загадку «Что можно увидеть с закрытыми глазами?». Если подходит инструмент — используй его."}]
    while True:
        text = input("Ты: ").strip()
        if text == "/exit":
            break
        messages.append({"role": "user", "content": text})
        answer = agent_answer(messages, TOOLS, FUNCTIONS)
        messages.append({"role": "assistant", "content": answer})
        print("Агент:", answer)
