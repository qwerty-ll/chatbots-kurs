import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def souvenir_tip():
    return random.choice([
        "Привези из Костромы сыр — местные сыроварни славятся на всю страну.",
        "Купи льняную скатерть или полотенце — костромской лён очень известен.",
        "Возьми магнит с Пожарной каланчой — главным символом города.",
        "Загляни в терем Снегурочки за сказочным сувениром.",
    ])


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def place_info(place):
    places = {
        "ипатьевский монастырь": "Древний монастырь XIV века на берегу реки Костромы — отсюда в 1613 году на царство призвали Михаила Романова.",
        "торговые ряды": "Огромный торговый комплекс XVIII–XIX веков в самом центре — тут и сейчас торгуют.",
        "пожарная каланча": "Каланча 1820-х годов в стиле классицизма — одна из самых красивых в России.",
        "терем снегурочки": "Сказочный деревянный терем, где живёт Снегурочка, с ледяной комнатой.",
    }
    return places.get(place.lower().strip(), f"Про место «{place}» Валера ещё узнает и расскажет!")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("souvenir_tip", "Советует, какой сувенир привезти из Костромы."),
    make_tool("place_info", "Рассказывает о достопримечательности Костромы по её названию.",
              {"place": {"type": "string", "description": "Название места, например: Ипатьевский монастырь"}}, ["place"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "souvenir_tip": lambda args: souvenir_tip(),
    "place_info": lambda args: place_info(args["place"]),
}

# ▶ Запусти этот файл — с тобой поговорит агент только с ТВОИМИ инструментами.
# Наш_бот.py этот кусок не запускает: он берёт отсюда только TOOLS и FUNCTIONS.
if __name__ == "__main__":
    from agent import agent_answer

    messages = [{"role": "system", "content": "Ты помощник. Если подходит инструмент — используй его."}]
    while True:
        text = input("Ты: ").strip()
        if text == "/exit":
            break
        messages.append({"role": "user", "content": text})
        answer = agent_answer(messages, TOOLS, FUNCTIONS)
        messages.append({"role": "assistant", "content": answer})
        print("Агент:", answer)
