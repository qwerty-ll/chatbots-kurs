# ТВОЁ: первый инструмент — с параметром: маршрут по теме
def route_selector(theme):
    routes = {
        "история": "Ипатьевский монастырь → Сусанинская площадь → Торговые ряды → Пожарная каланча.",
        "природа": "Набережная Волги → беседка Островского → парк «Центральный».",
        "сказка": "Терем Снегурочки → музей сыра → Торговые ряды за сувенирами.",
        "еда": "Музей сыра → кафе в Торговых рядах → Сусанинская площадь с мороженым.",
    }
    route = routes.get(theme.lower().strip())
    if route:
        return f"Маршрут «{theme}»: {route}"
    return "Классический маршрут: Сусанинская площадь → Торговые ряды → набережная Волги."


# ТВОЁ: второй инструмент — с параметром: острый факт по категории
def spicy_fact_teller(category):
    facts = {
        "секрет": "Пожарную каланчу построили так красиво, что по легенде император спросил, не дворец ли это.",
        "мудрость": "Иван Сусанин завёл врагов в болото и спас царя — с тех пор в Костроме говорят: «Не уверен в дороге — спроси местного, но не того».",
        "ирония": "Кострома — родина Снегурочки, но снег тут тает каждую весну, как положено.",
    }
    return facts.get(category.lower().strip(), "Факт: в Костроме больше 100 храмов и ни одного скучного жителя!")


