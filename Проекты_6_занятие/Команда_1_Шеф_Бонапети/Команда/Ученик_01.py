import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def chef_joke():
    tips = [
        "Если суп пересолен — смело говори, что это маринад!",
        "Главное правило кухни: не сгорело, а благородно карамелизировалось!",
        "Пельмени никогда не предадут, максимум — объединятся в один мегапельмень!",
    ]
    return random.choice(tips)


def chef_compliment():
    compliments = [
        "У тебя руки настоящего шефа — даже яичница выйдет как в ресторане!",
        "С таким аппетитом ты точно станешь лучшим дегустатором кухни!",
        "Ты режешь лук так красиво, что он плачет от восторга, а не ты!",
    ]
    return random.choice(compliments)


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def find_recipe(product):
    recipes = {
        "яйца": "омлет: взбей 2 яйца с молоком, жарь 3 минуты под крышкой",
        "картошка": "пюре: свари картошку, разомни с маслом и молоком",
        "макароны": "макароны по-флотски: отвари и обжарь с фаршем",
        "курица": "курица в духовке: натри солью и специями, запекай 40 минут",
    }
    dish = recipes.get(product.lower().strip())
    if dish:
        return f"Из продукта «{product}» можно приготовить {dish}. Готовь вместе с другом — так веселее!"
    return f"С продуктом «{product}» сделай салат или суп — почти всё вкусно в супе! Готовь вместе с другом — так веселее!"


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("chef_joke", "Возвращает весёлую поварскую шутку от шефа."),
    make_tool("chef_compliment", "Говорит случайный кулинарный комплимент пользователю."),
    make_tool("find_recipe", "Подсказывает рецепт по продукту, который назвал пользователь.",
              {"product": {"type": "string", "description": "Продукт, например: яйца, картошка, курица"}}, ["product"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "chef_joke": lambda args: chef_joke(),
    "chef_compliment": lambda args: chef_compliment(),
    "find_recipe": lambda args: find_recipe(args["product"]),
}

