import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def what_to_cook():
    ideas = [
        "Приготовь блинчики — это быстро, а радости на весь день!",
        "Сделай бутерброды-смайлики: хлеб, сыр и огурец вместо глаз.",
        "Свари гречку с котлетой — классика, которая не подводит.",
        "Испеки шарлотку: яблоки, мука, яйца и сахар — и десерт готов!",
    ]
    return random.choice(ideas)


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def cooking_advice(topic):
    advice = {
        "тесто": "Посыпь тесто мукой — тогда оно не будет слипаться!",
        "суп": "Соль добавляй в конце — так суп точно не пересолишь.",
        "блины": "Первый блин комом? Хорошо смажь сковороду и сильно её разогрей.",
        "мясо": "Дай мясу отдохнуть 5 минут после жарки — оно станет сочнее.",
    }
    tip = advice.get(topic.lower().strip(), "Начни с самого простого и готовь с другом — будет весело и не скучно!")
    return f"Совет по теме «{topic}»: {tip} Молодец!"


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("what_to_cook", "Подсказывает, что приготовить, если не знаешь, что сделать."),
    make_tool("cooking_advice", "Даёт кулинарный совет по теме (тесто, суп, блины, мясо и т.д.).",
              {"topic": {"type": "string", "description": "Тема совета, например: тесто, суп, блины"}}, ["topic"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "what_to_cook": lambda args: what_to_cook(),
    "cooking_advice": lambda args: cooking_advice(args["topic"]),
}

