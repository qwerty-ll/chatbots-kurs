from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def quick_lifehack():
    tips = [
        "Правило двух минут: если дело занимает меньше двух минут, сделай его сразу.",
        "Выпей стакан воды прямо сейчас — это мгновенно взбодрит организм.",
        "Делай пятиминутный перерыв каждый час, чтобы размяться и дать глазам отдохнуть.",
        "Запиши главную задачу на листке — записанные цели выполняются быстрее.",
    ]
    return random.choice(tips)


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def lifehack_by_topic(topic):
    hacks = {
        "сон": "Ложись в одно и то же время и убирай телефон за 30 минут до сна.",
        "уборка": "Включи любимую песню и убирайся, пока она играет, — 4 минуты и готово.",
        "учёба": "Объясни тему воображаемому другу — так сразу видно, что ты не понял.",
        "утро": "Собери рюкзак и одежду с вечера — утром сэкономишь 10 минут.",
        "спорт": "Положи кроссовки на видное место — так проще не пропустить тренировку.",
    }
    return hacks.get(topic.lower().strip(), f"Лайфхак для темы «{topic}»: начни с маленького шага прямо сейчас.")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("quick_lifehack", "Возвращает полезный и простой лайфхак на каждый день."),
    make_tool("lifehack_by_topic", "Даёт лайфхак по теме: сон, уборка, учёба, утро, спорт.",
              {"topic": {"type": "string", "description": "Тема лайфхака"}}, ["topic"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "quick_lifehack": lambda args: quick_lifehack(),
    "lifehack_by_topic": lambda args: lifehack_by_topic(args["topic"]),
}

