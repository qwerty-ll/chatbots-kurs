import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def daily_focus():
    tips = [
        "Выдели 1 главное дело на сегодня и начни с него.",
        "Работай спринтами: 25 минут фокуса, 5 минут отдыха.",
        "Убери телефон из поля зрения на ближайший час.",
        "Сделай самую неприятную задачу первой, чтобы освободить мысли.",
        "Разбей большую задачу на шаги по 15 минут — начать будет гораздо проще.",
        "Отключи уведомления на 25 минут, чтобы сфокусироваться на главном.",
    ]
    return random.choice(tips)


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def plan_task(task):
    return (f"План для «{task}»:\n"
            f"1) 5 минут — пойми, что именно нужно сделать.\n"
            f"2) 25 минут — сделай самую важную часть.\n"
            f"3) 5 минут — перерыв и стакан воды.\n"
            f"4) 15 минут — доделай и проверь результат.")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("daily_focus", "Возвращает короткую рекомендацию для фокусировки и продуктивной работы на день."),
    make_tool("plan_task", "Разбивает задачу пользователя на короткий план из шагов с таймером.",
              {"task": {"type": "string", "description": "Задача, например: сделать доклад по биологии"}}, ["task"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "daily_focus": lambda args: daily_focus(),
    "plan_task": lambda args: plan_task(args["task"]),
}

# ▶ Запусти этот файл — с тобой поговорит агент только с ТВОИМИ инструментами.
# Наш_бот.py этот кусок не запускает: он берёт отсюда только TOOLS и FUNCTIONS.
if __name__ == "__main__":
    from agent import agent_answer

    messages = [{"role": "system", "content": "Ты помощник. Если подходит инструмент — используй его."}]
    while True:
        text = input("Ты: ").strip()
        if text == "/exit":
            break
        messages.append({"role": "user", "content": text})
        answer = agent_answer(messages, TOOLS, FUNCTIONS)
        messages.append({"role": "assistant", "content": answer})
        print("Агент:", answer)
