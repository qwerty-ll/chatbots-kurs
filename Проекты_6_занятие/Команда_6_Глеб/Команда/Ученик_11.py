import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня — команда /sovet)
def wake_up_call():
    start = [
        "Мечты не платят по счетам. Что ты продал сегодня? Открой список клиентов и звони.",
        "Идея без действия стоит ноль рублей. Где твой первый клиент? Найди его до конца дня.",
        "Ты не устал — ты не начал. Какая задача висит три дня? Сделай её прямо сейчас.",
        "Рынок не ждёт, пока ты будешь готов. Что мешает запуститься? Запускайся сырым.",
    ]
    return random.choice(start)


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def check_idea(idea):
    score = len(idea.split())
    if score < 4:
        return f"Идея «{idea}» — это пока слово, а не бизнес. Кто клиент и за что он платит? Опиши в одном предложении."
    return (f"Идея «{idea}»: проверь три вещи — кто платит, сколько платит, где ты его найдёшь. "
            f"Есть ответы? Найди 3 клиентов за неделю. Нет — переделывай идею сегодня.")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("wake_up_call", "Выдаёт жёсткую отрезвляющую установку для стартапера, чтобы сломать иллюзии и заставить действовать (совет дня)."),
    make_tool("check_idea", "Жёстко проверяет бизнес-идею пользователя и говорит, что делать дальше.",
              {"idea": {"type": "string", "description": "Бизнес-идея пользователя"}}, ["idea"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "wake_up_call": lambda args: wake_up_call(),
    "check_idea": lambda args: check_idea(args["idea"]),
}

