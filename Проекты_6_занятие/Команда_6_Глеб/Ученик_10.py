# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def reality_check():
    tips = [
        "90% стартапов гибнут из-за расфокуса. Ты закрыл ключевую задачу на сегодня? Закрывай вкладки и иди продавать.",
        "Твои конкуренты прямо сейчас звонят твоим лидам. Почему ты полируешь презентацию, а не закрываешь сделки? Живо в CRM.",
        "Время — единственный невосполнимый актив. Сколько прибыли принёс твой последний час? Прекрати имитировать занятость и выдай результат.",
        "Пока ты рефлексируешь, твой кэш-флоу горит. Где деньги за прошлый спринт? Делай ключевые звонки прямо сейчас.",
    ]
    return random.choice(tips)


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def sovet_for_biznes(topic):
    sovet = {
        "продажи": "Факт: 80% сделок закрываются после 5-го контакта. Сколько раз ты написал клиенту? Пиши шестой раз сегодня.",
        "деньги": "Факт: бизнес умирает от кассового разрыва, а не от убытков. Ты знаешь остаток на счёте? Посчитай до вечера.",
        "команда": "Факт: один слабый сотрудник тянет вниз троих. Кто у тебя не делает результат? Поговори с ним завтра.",
        "реклама": "Факт: реклама без замера — это пожертвование. Сколько стоит один клиент? Посчитай и отключи то, что не окупается.",
    }
    return sovet.get(topic.lower().strip(),
                     f"Факт: в теме «{topic}» побеждает тот, кто делает. Что ты сделал за последний час? Встал и сделал первый шаг.")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("reality_check", "Возвращает жёсткий отрезвляющий пинок от инвестора для проверки продуктивности и возврата к работе."),
    make_tool("sovet_for_biznes", "Даёт жёсткий бизнес-совет по теме: продажи, деньги, команда, реклама.",
              {"topic": {"type": "string", "description": "Тема бизнес-совета"}}, ["topic"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "reality_check": lambda args: reality_check(),
    "sovet_for_biznes": lambda args: sovet_for_biznes(args["topic"]),
}

