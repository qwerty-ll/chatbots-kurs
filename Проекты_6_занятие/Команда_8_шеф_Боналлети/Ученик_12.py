import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def tip_of_day():
    return random.choice([
        "Наточи нож, чтобы не плакать от лука!",
        "Добавь масло в воду, чтобы макароны не слиплись.",
        "Мясо соли в конце жарки — так оно останется сочным.",
        "Положи в пакет с зеленью бумажное полотенце — она дольше будет свежей.",
    ])


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def find_recipe(product):
    p = product.lower()
    if "яйц" in p or "яиц" in p:
        return "Из продукта яйца можно сделать омлет."
    if "картош" in p:
        return "Из продукта картошка можно сделать пюре."
    if "молок" in p:
        return "Из продукта молоко можно сделать блинчики."
    if "сыр" in p:
        return "Из продукта сыр можно сделать горячие бутерброды."
    return f"Из продукта {product} можно сделать секретное блюдо!"


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("tip_of_day", "Дать кулинарный совет дня."),
    make_tool("find_recipe", "Найти рецепт по продукту.",
              {"product": {"type": "string", "description": "Продукт, например: яйца, картошка, молоко"}}, ["product"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "tip_of_day": lambda args: tip_of_day(),
    "find_recipe": lambda args: find_recipe(args["product"]),
}

