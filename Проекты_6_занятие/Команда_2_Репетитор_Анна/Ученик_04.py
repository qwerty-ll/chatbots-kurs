import random
from datetime import datetime

from agent import make_tool

# ТВОЁ: первый инструмент — без параметров (совет дня, случайный факт, комплимент…)
def praise():
    return random.choice([
        "Молодец!",
        "Отличная работа, так держать!",
        "Ты сегодня умнее вчерашнего себя!",
        "Пятёрка уже бежит к тебе в дневник!",
    ])


# ТВОЁ: второй инструмент — с параметром (рецепт по продукту, перевод слова, оценка ответа…)
def subject_rule(subject):
    rules = {
        "математика": "Площадь прямоугольника = длина × ширина. А от перемены мест множителей произведение не меняется!",
        "русский": "ЖИ-ШИ пиши с буквой И, ЧА-ЩА — с буквой А.",
        "английский": "С he/she/it к глаголу в Present Simple добавляй -s: she plays.",
        "физика": "Скорость = путь ÷ время. Проверь, в каких единицах ответ!",
        "история": "Крещение Руси — 988 год, князь Владимир.",
    }
    return rules.get(subject.lower().strip(), f"По предмету «{subject}» правило пока не знаю — спроси у учителя!")


# Описания для нейросети: она читает только их — пиши понятно
TOOLS = [
    make_tool("praise", "Хвалит ученика, когда он что-то сделал или решил."),
    make_tool("subject_rule", "Напоминает одно главное правило по школьному предмету.",
              {"subject": {"type": "string", "description": "Предмет: математика, русский, английский, физика, история"}},
              ["subject"]),
]

# Имя инструмента -> какую функцию запустить
FUNCTIONS = {
    "praise": lambda args: praise(),
    "subject_rule": lambda args: subject_rule(args["subject"]),
}

# ▶ Запусти этот файл — с тобой поговорит агент только с ТВОИМИ инструментами.
# Наш_бот.py этот кусок не запускает: он берёт отсюда только TOOLS и FUNCTIONS.
if __name__ == "__main__":
    from agent import agent_answer

    messages = [{"role": "system", "content": "Ты помощник. Если подходит инструмент — используй его."}]
    while True:
        text = input("Ты: ").strip()
        if text == "/exit":
            break
        messages.append({"role": "user", "content": text})
        answer = agent_answer(messages, TOOLS, FUNCTIONS)
        messages.append({"role": "assistant", "content": answer})
        print("Агент:", answer)
